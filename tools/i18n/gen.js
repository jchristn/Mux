// Generate the desktop string catalogs from their authored sources.
//
//   node tools/i18n/gen.js           regenerate both .cs catalogs in place
//   node tools/i18n/gen.js --check   write nothing; exit 1 (with a per-key report) when either
//                                    checked-in .cs file differs from what this script produces
//
// Run from any directory (paths resolve relative to this file). Needs only node, no packages.
// The Touchstone suite "I18nCatalogs" (src/Test.Shared/Suites/I18nCatalogsSuite.cs) runs --check.
//
// Catalogs:
// 1. src/Mux.Desktop.Core/I18n/DesktopStrings.cs from tools/i18n/desktop-i18n.js.
//    desktop-i18n.js exports { "<key>": { en, es, pt, fr, it, de, zh, ar, ru, ms, hi }, ... }.
//    English (en) is required per key; any locale omitted for a key falls back to English at
//    runtime (LocalizationService). Keys that intentionally stay English (long help text) supply
//    only `en`. Keys named after dashboard keys (e.g. "nav.endpoints") OVERRIDE the dashboard pack
//    for the desktop (LocalizationService merges DesktopStrings over DashboardStrings).
// 2. src/Mux.Desktop.Core/I18n/DashboardStrings.cs from the web dashboard's I18N packs
//    (var I18N={...} in src/Mux.Server/DashboardTemplate.cs), limited to and ordered by the key
//    list in tools/i18n/dashboard-keys.js, plus that file's `extra` translations for keys a
//    locale's pack does not have yet.
//
// Do not edit either .cs file by hand: add or change strings in the sources above and regenerate.
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const LANGS = ['en', 'es', 'pt', 'fr', 'it', 'de', 'zh', 'ar', 'ru', 'ms', 'hi'];
const root = path.join(__dirname, '..', '..');
const i18nDir = path.join(root, 'src', 'Mux.Desktop.Core', 'I18n');
const desktopOut = path.join(i18nDir, 'DesktopStrings.cs');
const dashboardOut = path.join(i18nDir, 'DashboardStrings.cs');
const dashboardTemplate = path.join(root, 'src', 'Mux.Server', 'DashboardTemplate.cs');

const args = process.argv.slice(2);
const checkMode = args.includes('--check');
const unknown = args.filter(a => a !== '--check');
if (unknown.length) {
  console.error('usage: node tools/i18n/gen.js [--check]');
  process.exit(2);
}

function csEsc(s) {
  return s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\r/g, '').replace(/\n/g, '\\n');
}

function emitLocale(lang, map) {
  let out = '            all["' + lang + '"] = new Dictionary<string, string>(StringComparer.Ordinal)\n            {\n';
  for (const k of Object.keys(map)) {
    out += '                { "' + csEsc(k) + '", "' + csEsc(map[k]) + '" },\n';
  }
  out += '            };\n\n';
  return out;
}

const BUILD_HEAD =
  '            Dictionary<string, Dictionary<string, string>> all =\n' +
  '                new Dictionary<string, Dictionary<string, string>>(StringComparer.OrdinalIgnoreCase);\n\n';
const BUILD_TAIL = '            return all;\n        }\n    }\n}\n';

// ---------------------------------------------------------------- DesktopStrings.cs

function generateDesktop() {
  const catalog = require('./desktop-i18n.js');
  const keys = Object.keys(catalog);
  let bad = 0;
  for (const k of keys) {
    if (!catalog[k] || typeof catalog[k].en !== 'string' || catalog[k].en.length === 0) {
      console.error('MISSING en for key:', k);
      bad++;
    }
  }
  if (bad) { throw new Error(bad + ' key(s) missing English in desktop-i18n.js'); }

  // A key appears in a locale only when that locale has a translation (English always; others
  // only when present) so missing ones fall back to English at runtime.
  const byLocale = {};
  for (const lang of LANGS) { byLocale[lang] = {}; }
  for (const k of keys) {
    for (const lang of LANGS) {
      const v = catalog[k][lang];
      if (typeof v === 'string' && v.length > 0) { byLocale[lang][k] = v; }
    }
  }

  let out = '';
  out += 'namespace Mux.Desktop.I18n\n{\n';
  out += '    using System;\n';
  out += '    using System.Collections.Generic;\n\n';
  out += '    /// <summary>\n';
  out += '    /// Desktop-specific string catalogs. GENERATED by <c>tools/i18n/gen.js</c> from\n';
  out += '    /// <c>tools/i18n/desktop-i18n.js</c> — do not edit by hand; edit the authored table and regenerate.\n';
  out += '    /// Covers every desktop window/form/dialog label; keys named after dashboard keys override the\n';
  out += '    /// shared pack for the desktop. Merged over <see cref="DashboardStrings"/> by\n';
  out += '    /// <see cref="LocalizationService"/>; any locale missing a key falls back to English.\n';
  out += '    /// Regenerate with <c>node tools/i18n/gen.js</c>; <c>node tools/i18n/gen.js --check</c> fails when\n';
  out += '    /// this file no longer matches its source.\n';
  out += '    /// </summary>\n';
  out += '    internal static class DesktopStrings\n    {\n';
  out += '        /// <summary>\n';
  out += '        /// Build the per-locale (key → value) catalogs for the desktop-specific strings.\n';
  out += '        /// </summary>\n';
  out += '        /// <returns>A dictionary of locale code to its (key → value) map.</returns>\n';
  out += '        internal static Dictionary<string, Dictionary<string, string>> Build()\n        {\n';
  out += BUILD_HEAD;
  for (const lang of LANGS) { out += emitLocale(lang, byLocale[lang]); }
  out += BUILD_TAIL;

  const untranslated = {};
  for (const lang of LANGS) { untranslated[lang] = keys.length - Object.keys(byLocale[lang]).length; }
  return { file: desktopOut, text: out, summary: keys.length + ' keys; untranslated (fall back to en) per locale: ' + JSON.stringify(untranslated) };
}

// ---------------------------------------------------------------- DashboardStrings.cs

function readDashboardPacks() {
  const txt = fs.readFileSync(dashboardTemplate, 'utf8');
  const start = txt.indexOf('var I18N={');
  const end = start < 0 ? -1 : txt.indexOf('\n};\n', start);
  if (start < 0 || end < 0) { throw new Error('could not find "var I18N={ ... };" in ' + dashboardTemplate); }
  // The template is a C# raw string literal, so the JavaScript between the markers is verbatim.
  return vm.runInNewContext('(' + txt.slice(start + 'var I18N='.length, end + 2) + ')', {});
}

function generateDashboard() {
  const spec = require('./dashboard-keys.js');
  const packs = readDashboardPacks();
  const extra = spec.extra || {};
  const seen = new Set();
  const problems = [];
  for (const k of spec.keys) {
    if (seen.has(k)) { problems.push('duplicate key in dashboard-keys.js: ' + k); }
    seen.add(k);
    if (!(packs.en && typeof packs.en[k] === 'string') && !(extra.en && typeof extra.en[k] === 'string')) {
      problems.push('key not in the dashboard en pack: ' + k);
    }
  }
  for (const lang of Object.keys(extra)) {
    if (!LANGS.includes(lang)) { problems.push('unknown locale in extra: ' + lang); continue; }
    for (const k of Object.keys(extra[lang])) {
      if (!seen.has(k)) { problems.push('extra.' + lang + ' names a key not in keys: ' + k); }
    }
  }
  if (problems.length) { throw new Error('dashboard-keys.js:\n  ' + problems.join('\n  ')); }

  const byLocale = {};
  const shadowed = [];
  for (const lang of LANGS) {
    byLocale[lang] = {};
    const pack = packs[lang] || {};
    const ext = extra[lang] || {};
    for (const k of spec.keys) {
      const pv = pack[k];
      if (typeof pv === 'string' && pv.length > 0) {
        byLocale[lang][k] = pv;
        if (typeof ext[k] === 'string') { shadowed.push(lang + ':' + k); }
      } else if (typeof ext[k] === 'string' && ext[k].length > 0) {
        byLocale[lang][k] = ext[k];
      }
    }
  }
  if (shadowed.length) {
    console.error('NOTE: the dashboard packs now carry these; drop them from dashboard-keys.js extra: ' + shadowed.join(' '));
  }

  let out = '';
  out += 'namespace Mux.Desktop.I18n\n{\n';
  out += '    using System;\n';
  out += '    using System.Collections.Generic;\n\n';
  out += '    /// <summary>\n';
  out += '    /// Chrome string catalogs ported verbatim from the <c>mux serve</c> dashboard I18N packs\n';
  out += '    /// (<c>src/Mux.Server/DashboardTemplate.cs</c>) so the desktop app and the web dashboard share the\n';
  out += '    /// same authored translations for the same keys. GENERATED by <c>tools/i18n/gen.js</c> from those\n';
  out += '    /// packs and the key list in <c>tools/i18n/dashboard-keys.js</c> — do not edit by hand; regenerate\n';
  out += '    /// with <c>node tools/i18n/gen.js</c> (<c>--check</c> fails when this file no longer matches).\n';
  out += '    /// Covers the "chrome" tier (nav, actions, table, toasts, empty states, column headers, tags, chat,\n';
  out += '    /// settings section headers); long help text stays English by design, matching the dashboard\'s\n';
  out += '    /// own translated/untranslated boundary.\n';
  out += '    /// </summary>\n';
  out += '    internal static class DashboardStrings\n    {\n';
  out += '        /// <summary>The locale codes this catalog carries, English first.</summary>\n';
  out += '        internal static IReadOnlyList<string> Locales { get; } = new List<string>\n        {\n';
  out += '            ' + LANGS.map(l => '"' + l + '"').join(', ') + '\n';
  out += '        };\n\n';
  out += '        /// <summary>\n';
  out += '        /// Build the per-locale (key → value) catalogs.\n';
  out += '        /// </summary>\n';
  out += '        /// <returns>A dictionary of locale code to its (key → value) map.</returns>\n';
  out += '        internal static Dictionary<string, Dictionary<string, string>> Build()\n        {\n';
  out += BUILD_HEAD;
  for (const lang of LANGS) { out += emitLocale(lang, byLocale[lang]); }
  out += BUILD_TAIL;

  const counts = {};
  for (const lang of LANGS) { counts[lang] = Object.keys(byLocale[lang]).length; }
  return { file: dashboardOut, text: out, summary: spec.keys.length + ' keys; per locale: ' + JSON.stringify(counts) };
}

// ---------------------------------------------------------------- --check reporting

// Parse a catalog .cs into { lang: Map(key -> value) } so a mismatch can be reported per key.
function parseCatalog(text) {
  const unesc = s => s.replace(/\\(.)/g, (m, c) => (c === 'n' ? '\n' : c));
  const out = {};
  let cur = null;
  for (const line of text.split(/\r?\n/)) {
    let m = line.match(/^\s*all\["(\w+)"\] = new/);
    if (m) { cur = m[1]; out[cur] = new Map(); continue; }
    m = line.match(/^\s*\{ "((?:[^"\\]|\\.)*)", "((?:[^"\\]|\\.)*)" \},\s*$/);
    if (m && cur) { out[cur].set(unesc(m[1]), unesc(m[2])); }
  }
  return out;
}

function describeDiff(actual, expected) {
  const a = parseCatalog(actual);
  const e = parseCatalog(expected);
  const lines = [];
  for (const lang of LANGS) {
    const am = a[lang] || new Map();
    const em = e[lang] || new Map();
    const onlyFile = [...am.keys()].filter(k => !em.has(k));
    const onlySource = [...em.keys()].filter(k => !am.has(k));
    const changed = [...am.keys()].filter(k => em.has(k) && em.get(k) !== am.get(k));
    const common = [...am.keys()].filter(k => em.has(k));
    const commonExpected = [...em.keys()].filter(k => am.has(k));
    const reordered = common.join('\u0000') !== commonExpected.join('\u0000');
    if (onlyFile.length) { lines.push('  ' + lang + ': in the .cs but not the source (' + onlyFile.length + '): ' + onlyFile.join(' ')); }
    if (onlySource.length) { lines.push('  ' + lang + ': in the source but not the .cs (' + onlySource.length + '): ' + onlySource.join(' ')); }
    if (changed.length) { lines.push('  ' + lang + ': value differs (' + changed.length + '): ' + changed.join(' ')); }
    if (reordered) { lines.push('  ' + lang + ': key order differs'); }
  }
  if (!lines.length) {
    const al = actual.split('\n');
    const el = expected.split('\n');
    let i = 0;
    while (i < al.length && i < el.length && al[i] === el[i]) { i++; }
    lines.push('  formatting differs first at line ' + (i + 1) + ':');
    lines.push('    .cs:       ' + JSON.stringify(al[i]));
    lines.push('    generated: ' + JSON.stringify(el[i]));
  }
  return lines.join('\n');
}

// ---------------------------------------------------------------- main

const results = [generateDesktop(), generateDashboard()];
let stale = 0;
for (const r of results) {
  const rel = path.relative(root, r.file);
  if (checkMode) {
    const actual = fs.existsSync(r.file) ? fs.readFileSync(r.file, 'utf8') : '';
    if (actual === r.text) {
      console.error('OK     ' + rel + ' (' + r.summary + ')');
    } else if (actual.replace(/\r\n/g, '\n') === r.text) {
      // A CRLF working-tree checkout (core.autocrlf) of an LF file in git is not drift.
      console.error('OK     ' + rel + ' (CRLF checkout; content matches)');
    } else {
      stale++;
      console.error('STALE  ' + rel + ' differs from what tools/i18n/gen.js generates:');
      console.error(describeDiff(actual, r.text));
    }
  } else {
    fs.writeFileSync(r.file, r.text, 'utf8');
    console.error('Wrote  ' + rel + ' ' + Buffer.byteLength(r.text, 'utf8') + ' bytes (' + r.summary + ')');
  }
}
if (stale) {
  console.error(stale + ' catalog(s) out of date. Move hand edits into the sources named above, then run: node tools/i18n/gen.js');
  process.exit(1);
}
